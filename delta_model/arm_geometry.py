"""Shared geometric points for the three symmetric upper arms."""

import math

from delta_model.conventions import CartesianPoint, CartesianPosition
from delta_model.geometry import DeltaGeometry

_SQRT_3_OVER_2 = math.sqrt(3.0) / 2.0
_RADIAL_VECTORS = (
    (0.0, -1.0),
    (_SQRT_3_OVER_2, 0.5),
    (-_SQRT_3_OVER_2, 0.5),
)


def arm_radial_vector(arm_index: int) -> tuple[float, float]:
    """Return the arm's outward XY unit vector in base-frame order."""

    if arm_index not in (1, 2, 3):
        raise ValueError("arm_index must be 1, 2 or 3")
    return _RADIAL_VECTORS[arm_index - 1]


def shoulder_point(geometry: DeltaGeometry, arm_index: int) -> CartesianPoint:
    """Return the fixed shoulder point for one arm."""

    radial_x, radial_y = arm_radial_vector(arm_index)
    return CartesianPoint(
        x_m=geometry.base_joint_radius_m * radial_x,
        y_m=geometry.base_joint_radius_m * radial_y,
        z_m=0.0,
    )


def knee_point(geometry: DeltaGeometry, arm_index: int, angle_rad: float) -> CartesianPoint:
    """Return the knee point generated by one actuated shoulder angle."""

    radial_x, radial_y = arm_radial_vector(arm_index)
    shoulder = shoulder_point(geometry, arm_index)
    radial_extension_m = geometry.upper_arm_length_m * math.cos(angle_rad)
    return CartesianPoint(
        x_m=shoulder.x_m + radial_extension_m * radial_x,
        y_m=shoulder.y_m + radial_extension_m * radial_y,
        z_m=-geometry.upper_arm_length_m * math.sin(angle_rad),
    )


def platform_attachment_point(
    geometry: DeltaGeometry,
    position: CartesianPosition,
    arm_index: int,
) -> CartesianPoint:
    """Return one platform attachment in the untranslated base orientation."""

    radial_x, radial_y = arm_radial_vector(arm_index)
    return CartesianPoint(
        x_m=position.x_m + geometry.platform_joint_radius_m * radial_x,
        y_m=position.y_m + geometry.platform_joint_radius_m * radial_y,
        z_m=position.z_m,
    )


def virtual_sphere_center(
    geometry: DeltaGeometry,
    arm_index: int,
    angle_rad: float,
) -> CartesianPoint:
    """Shift a knee by the negative platform offset to constrain its center."""

    radial_x, radial_y = arm_radial_vector(arm_index)
    knee = knee_point(geometry, arm_index, angle_rad)
    return CartesianPoint(
        x_m=knee.x_m - geometry.platform_joint_radius_m * radial_x,
        y_m=knee.y_m - geometry.platform_joint_radius_m * radial_y,
        z_m=knee.z_m,
    )
